export function iconEl(name, cls = "") {
  const span = document.createElement("span");
  span.style.display = "inline-grid";
  span.innerHTML = icon(name, cls);
  return span.firstChild;
}

export function toast(msg, kind = "") {
  const box = document.getElementById("toasts");
  const ico = kind === "err" ? "alert" : kind === "ok" ? "check" : "info";
  const el = h("div", { class: `toast ${kind}`, html: icon(ico) }, h("div", {}, msg));
  box.append(el);
  setTimeout(() => el.remove(), kind === "err" ? 7000 : 3500);
}

export function modal({ title, body, footer, wide = false, onClose } = {}) {
  const bg = h("div", { class: "modal-bg" });
  const close = () => { bg.remove(); document.removeEventListener("keydown", esc); onClose && onClose(); };
  const esc = (e) => { if (e.key === "Escape") close(); };
  document.addEventListener("keydown", esc);
  const box = h("div", { class: `modal ${wide ? "wide" : ""}` },
    h("div", { class: "modal-head" }, h("h3", {}, title || ""),
      h("button", { class: "btn ghost sm icon-only", html: icon("x"), onclick: close })),
    h("div", { class: "modal-body" }, body),
    footer ? h("div", { class: "modal-foot" }, footer) : null);
  bg.append(box);
  bg.addEventListener("mousedown", (e) => { if (e.target === bg) close(); });
  document.body.append(bg);
  return { close, el: box };
}

export function confirmDialog(message, { okText = "确定", danger = false } = {}) {
  return new Promise((resolve) => {
    let done = false;
    const finish = (v) => { if (!done) { done = true; m.close(); resolve(v); } };
    const m = modal({
      title: "请确认",
      body: h("div", {}, message),
      footer: [
        h("button", { class: "btn", onclick: () => finish(false) }, "取消"),
        h("button", { class: `btn ${danger ? "danger" : "primary"}`, onclick: () => finish(true) }, okText),
      ],
      onClose: () => { if (!done) { done = true; resolve(false); } },
    });
  });
}

export function fmtSize(n) {
  if (n == null) return "";
  if (n < 1024) return `${n} B`;
  if (n < 1048576) return `${(n / 1024).toFixed(1)} KB`;
  if (n < 1073741824) return `${(n / 1048576).toFixed(1)} MB`;
  return `${(n / 1073741824).toFixed(2)} GB`;
}

export function fmtTime(ts) {
  const d = new Date(ts * 1000);
  const now = new Date();
  const same = d.toDateString() === now.toDateString();
  const p = (x) => String(x).padStart(2, "0");
  return same ? `${p(d.getHours())}:${p(d.getMinutes())}` : `${d.getMonth() + 1}/${d.getDate()} ${p(d.getHours())}:${p(d.getMinutes())}`;
}

export function fmtClock(sec) {
  sec = Math.max(0, Number(sec) || 0);
  const hh = Math.floor(sec / 3600), mm = Math.floor((sec % 3600) / 60), ss = sec % 60;
  return `${String(hh).padStart(2, "0")}:${String(mm).padStart(2, "0")}:${ss.toFixed(3).padStart(6, "0")}`;
}

export function parseClock(s) {
  s = String(s).trim().replace(",", ".");
  if (/^\d+(\.\d+)?$/.test(s)) return parseFloat(s);
  const parts = s.split(":").map(Number);
  if (parts.some(isNaN)) return NaN;
  return parts.reduce((acc, v) => acc * 60 + v, 0);
}

export function basename(p) {
  return String(p || "").split(/[\\/]/).pop();
}

export const KIND_ICON = { video: "film", audio: "music", image: "image", subtitle: "captions", text: "text", dir: "folder", other: "file" };

export function kindOf(path) {
  const ext = String(path).toLowerCase().split(".").pop();
  if (["mp4", "mov", "mkv", "webm", "avi", "flv", "m4v", "ts", "wmv", "mpg", "mpeg", "3gp"].includes(ext)) return "video";
  if (["mp3", "wav", "m4a", "aac", "flac", "ogg", "opus", "wma"].includes(ext)) return "audio";
  if (["jpg", "jpeg", "png", "webp", "bmp", "gif"].includes(ext)) return "image";
  if (["srt", "vtt", "ass", "ssa"].includes(ext)) return "subtitle";
  if (["txt", "md", "json", "csv", "log"].includes(ext)) return "text";
  return "other";
}

export function autosize(ta, max = 260) {
  ta.style.height = "auto";
  ta.style.height = Math.min(max, ta.scrollHeight) + "px";
}
